/**
 * Package the dashboard as a single Windows executable (Node Single Executable Application).
 *   npm run build   ->  dist/HRA-Submission-Tool.exe
 *
 * Steps: embed public/ into src/web/embedded.ts, bundle with esbuild to CommonJS, build the SEA blob,
 * copy node.exe and inject the blob with postject. Falls back to a portable zip layout on failure.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { build, type Plugin } from 'esbuild';

const root = path.resolve(import.meta.dirname, '..');
const dist = path.join(root, 'dist');
const embeddedTs = path.join(root, 'src', 'web', 'embedded.ts');
const embeddedBackup = `// Overwritten by scripts/build.ts with the contents of public/ when packaging; empty in development.
export const EMBEDDED: Record<string, string> = {};
`;

function embedPublic(): void {
  const pub = path.join(root, 'public');
  const files: Record<string, string> = {};
  for (const f of fs.readdirSync(pub)) files[f] = fs.readFileSync(path.join(pub, f), 'utf8');
  fs.writeFileSync(embeddedTs, `// GENERATED by scripts/build.ts — do not edit.\nexport const EMBEDDED: Record<string, string> = ${JSON.stringify(files)};\n`);
}

/**
 * playwright-core's pre-bundled lib/coreBundle.js reads its package.json and browsers.json with a dynamic
 * `require(path.join(packageRoot, ...))`. Inside a Single Executable Application `require` only knows
 * built-in modules, so inline both JSON files at bundle time.
 */
function playwrightPackageStub(): Plugin {
  return {
    name: 'playwright-json-inline',
    setup(b) {
      b.onLoad({ filter: /playwright-core[\\/]lib[\\/](coreBundle|package|serverRegistry)\.js$/ }, (args) => {
        const pwRoot = path.join(root, 'node_modules', 'playwright-core');
        let contents = fs.readFileSync(args.path, 'utf8');
        for (const file of ['package.json', 'browsers.json']) {
          const json = fs.readFileSync(path.join(pwRoot, file), 'utf8').trim();
          const re = new RegExp(`require\\(import_path\\d+\\.default\\.join\\(packageRoot, "${file.replace('.', '\\.')}"\\)\\)`, 'g');
          contents = contents.replace(re, `(${json})`);
        }
        return { contents, loader: 'js' };
      });
    },
  };
}

async function main(): Promise<void> {
  try {
    fs.rmSync(dist, { recursive: true, force: true, maxRetries: 3 });
  } catch (err) {
    const running = fs.existsSync(dist) ? fs.readdirSync(dist).filter((f) => f.endsWith('.exe')) : [];
    throw new Error(
      `Could not clear ${dist} (${(err as NodeJS.ErrnoException).code}). ` +
        (running.length ? `Close the running ${running.join(', ')} first, then run the build again.` : 'Close anything that has files in dist/ open and try again.'),
    );
  }
  fs.mkdirSync(dist, { recursive: true });
  embedPublic();
  try {
    await build({
      entryPoints: [path.join(root, 'src', 'index.ts')],
      bundle: true,
      platform: 'node',
      format: 'cjs',
      target: 'node24',
      outfile: path.join(dist, 'app.cjs'),
      sourcemap: false,
      minify: false,
      logLevel: 'info',
      define: { 'import.meta.url': '__filename' },
      plugins: [playwrightPackageStub()],
    });
  } finally {
    fs.writeFileSync(embeddedTs, embeddedBackup);
  }

  const seaConfig = path.join(dist, 'sea-config.json');
  fs.writeFileSync(seaConfig, JSON.stringify({ main: 'app.cjs', output: 'sea-prep.blob', disableExperimentalSEAWarning: true, useCodeCache: false }, null, 2));
  execFileSync(process.execPath, ['--experimental-sea-config', seaConfig], { cwd: dist, stdio: 'inherit' });

  const exe = path.join(dist, 'HRA-Submission-Tool.exe');
  fs.copyFileSync(process.execPath, exe);
  // postject is a CLI; run it through node so no global install is needed.
  const postject = path.join(root, 'node_modules', 'postject', 'dist', 'cli.js');
  execFileSync(process.execPath, [postject, exe, 'NODE_SEA_BLOB', path.join(dist, 'sea-prep.blob'), '--sentinel-fuse', 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2'], { stdio: 'inherit' });

  for (const f of ['sea-prep.blob', 'sea-config.json']) fs.rmSync(path.join(dist, f), { force: true });
  fs.copyFileSync(path.join(root, 'README.md'), path.join(dist, 'README.md'));
  console.log(`\nBuilt ${exe} (${(fs.statSync(exe).size / 1e6).toFixed(1)} MB)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
